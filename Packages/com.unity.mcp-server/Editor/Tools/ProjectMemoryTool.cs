                File.WriteAllText(path, starter);
                AssetDatabase.Refresh();
            }

            var content = File.ReadAllText(path);
            return CreateSuccessResponse(new
            {
                path = "Assets/Editor/UnityMCP/Memory/" + DesignDocFileName,
                content = content
            }, "Living design document retrieved");
        }

        private object UpdateLivingDesignDoc(MemoryParams args)
        {
            // For simplicity in v1, we accept full new content via the "content" field when action=update_design_doc
            // In practice the agent will read first, then send back an improved version.
            if (string.IsNullOrWhiteSpace(args.content))
            {
                return CreateErrorResponse("content (full new document) is required for update_design_doc");
            }

            var path = Path.Combine(MemoryRoot, DesignDocFileName);
            File.WriteAllText(path, args.content);
            AssetDatabase.Refresh();

            return CreateSuccessResponse(new
            {
                updated = true,
                path = "Assets/Editor/UnityMCP/Memory/" + DesignDocFileName,
                length = args.content.Length
            }, "Living design document updated");
        }

        /// <summary>
        /// The crown jewel of the memory system. Synthesizes the living design document,
        /// recent recorded insights, and project model to give grounded, context-aware suggestions.
        /// This is what makes the AI feel like it has developed real taste for *this* game.
        /// </summary>
        private object GenerateSuggestion(MemoryParams args)
        {
            if (string.IsNullOrWhiteSpace(args.goal))
            {
                return CreateErrorResponse("goal is required for memory.suggest (e.g. 'Improve the feel of the dash ability')");
            }

            var goal = args.goal;
            var focus = args.focusArea ?? "general";

            // Load all available context
            var designDocPath = Path.Combine(MemoryRoot, DesignDocFileName);
            string designDoc = File.Exists(designDocPath) ? File.ReadAllText(designDocPath) : "No living design document exists yet.";

            var insightsPath = Path.Combine(MemoryRoot, InsightsFileName);
            var recentInsights = new List<string>();
            if (File.Exists(insightsPath))
            {
                recentInsights = File.ReadAllLines(insightsPath)
                    .Reverse()
                    .Take(12)
                    .ToList();
            }

            var modelPath = Path.Combine(MemoryRoot, ProjectModelFileName);
            string modelSummary = File.Exists(modelPath) ? "Project model exists and was last rebuilt recently." : "No project model indexed yet (run memory.rebuild).";

            // Build a rich, structured suggestion payload
            // In a more advanced version this could call an LLM internally. For now we return
            // extremely high-signal structured context that any good agent can reason over.
            var suggestion = new
            {
                goal = goal,
                focusArea = focus,
                synthesizedContext = new
                {
                    livingDesignDocExcerpt = designDoc.Length > 2400 ? designDoc.Substring(0, 2400) + "\n... (truncated)" : designDoc,
                    recentInsights = recentInsights,
                    projectModelStatus = modelSummary
                },
                recommendedApproach = new[]
                {
                    "Review the 'Current Known Good Feel' and 'Recent Decisions' sections of the design doc first.",
                    "Look at quantitative data from previous observations stored in insights.",
                    "Propose changes that respect the core values stated in the Living Design Document.",
                    "After implementing, use playmode.observe + memory.recordInsight to close the learning loop."
                },
                promptForAgent = $"You are an expert designer for this specific game. Goal: {goal}. Use the provided living design document and past insights to propose concrete, measurable next steps. Be specific with numbers and references to existing systems."
            };

            return CreateSuccessResponse(suggestion, $"Suggestion generated for: {goal}");
        }
    }
}